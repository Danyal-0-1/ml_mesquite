"""Run every numeric check of brief §9 and write the results to docs/VALIDATION.md.

    python scripts/validate.py            # full Monte Carlo sizes, rewrites docs/VALIDATION.md
    python scripts/validate.py --quick    # smaller samples, prints only

Exit status 1 if any check fails. Checks whose data are absent are reported as skipped.
"""

from __future__ import annotations

import argparse
import datetime as dt
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from mesqsim import validation  # noqa: E402
from mesqsim.validation import run_checks  # noqa: E402

FIGURES = [
    # (file under docs/figures, caption) — listed when the file exists
    ("stick_figure_amass.png", "AMASS → Mesquite segments: one walking sequence drawn with generic bone lengths "
     "(check 10)."),
    ("stick_figure_synthetic.png", "The same mapping on a synthetic walk (used until AMASS is downloaded): "
     "subject's left in blue, right in orange, +Z up."),
    ("diodem_relative_heading.png", "DIODEM arm exp01, hinge seg2 → seg3: six-axis VQF relative heading against "
     "optical truth (check 11.3). No claims are drawn from it in Step 1."),
]


def git_commit() -> str:
    try:
        sha = subprocess.run(["git", "rev-parse", "HEAD"], cwd=ROOT, capture_output=True, text=True, check=True)
        dirty = subprocess.run(["git", "status", "--porcelain"], cwd=ROOT, capture_output=True, text=True)
        return sha.stdout.strip()[:12] + ("+dirty" if dirty.stdout.strip() else "")
    except (OSError, subprocess.CalledProcessError):
        return "unknown"


def status_text(passed: bool | None) -> str:
    return {True: "pass", False: "**FAIL**", None: "skipped (data absent)"}[passed]


def render(results, commit: str, date: str) -> str:
    lines = [
        "# Validation",
        "",
        "*Generated by `python scripts/validate.py` (run by `bash scripts/check_all.sh`). Do not edit by hand;*",
        "*the text of each check lives in `mesqsim/validation.py`.*",
        "",
        f"**Latest run:** {date}, commit `{commit}` (the code that was checked; `+dirty` means uncommitted changes).",
        "",
        f"**Summary:** {sum(r.passed is True for _, r in results)} passed, "
        f"{sum(r.passed is False for _, r in results)} failed, "
        f"{sum(r.passed is None for _, r in results)} skipped, of {len(results)} checks.",
        "",
        "| # | check | expected | latest result | status |",
        "|---|---|---|---|---|",
    ]
    for chk, res in results:
        lines.append(f"| {chk.id} | {chk.title} | {chk.expected} | {res.result} | {status_text(res.passed)} |")
    lines += ["", "## What each check does and why", ""]
    for chk, _ in results:
        lines += [
            f"### {chk.id} {chk.title}",
            "",
            f"- **What:** {chk.what}",
            f"- **Why:** {chk.why}",
            f"- **Expected:** {chk.expected}",
            f"- **Command:** `{chk.command}`",
            "",
        ]
    present = [(f, c) for f, c in FIGURES if (ROOT / "docs" / "figures" / f).is_file()]
    lines += ["## Figures", ""]
    if not present:
        lines.append("No figures yet.")
    for f, cap in present:
        lines += [f"![{cap}](figures/{f})", "", f"*{cap}*", ""]
    return "\n".join(lines).rstrip() + "\n"


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--quick", action="store_true", help="smaller Monte Carlo samples; do not write the doc")
    args = ap.parse_args()
    sys.stdout.reconfigure(encoding="utf-8", errors="replace")  # Windows consoles default to cp1252
    _ = validation  # the import registers the checks
    commit = git_commit()  # before anything is written
    results = run_checks(quick=args.quick)
    for chk, res in results:
        print(f"[{status_text(res.passed):>8}] {chk.id:<5} {chk.title}: {res.result}")
    if not args.quick:
        date = dt.datetime.now(dt.UTC).strftime("%Y-%m-%d %H:%M UTC")
        (ROOT / "docs" / "VALIDATION.md").write_text(render(results, commit, date), encoding="utf-8", newline="\n")
        print("wrote docs/VALIDATION.md")
    failed = sum(r.passed is False for _, r in results)
    print("VALIDATION:", "PASS" if failed == 0 else f"FAIL ({failed})")
    return 1 if failed else 0


if __name__ == "__main__":
    sys.exit(main())
